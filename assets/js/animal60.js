  const ANCHOR_DATE_MS = Date.UTC(1900, 0, 1);
  const ANCHOR_GZ = 11;
  const MS_PER_DAY = 86400000;

  function calcDestinyNumber(y, m, d){
    if (!Number.isFinite(y) || !Number.isFinite(m) || !Number.isFinite(d)) return null;
    if (m < 1 || m > 12 || d < 1 || d > 31) return null;
    const target = Date.UTC(y, m - 1, d);
    if (isNaN(target)) return null;
    const days = Math.round((target - ANCHOR_DATE_MS) / MS_PER_DAY);
    let n = ((ANCHOR_GZ - 1 + days) % 60 + 60) % 60 + 1;
    return n;
  }

